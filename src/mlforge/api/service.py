import json
import os
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from mlforge.api.schemas import (
    CustomerFeatures,
    PredictionResponse,
)

MODEL_DIR = Path(os.getenv("MLFORGE_MODEL_DIR", "artifacts/tuning"))


class ModelService:
    """Production inference wrapper around a fitted pipeline."""

    def __init__(self, model_dir: Path = MODEL_DIR):
        model_path = model_dir / "best_model.joblib"
        metadata_path = model_dir / "metadata.json"

        if not model_path.is_file():
            raise FileNotFoundError(f"Model artifact missing: {model_path}")

        if not metadata_path.is_file():
            raise FileNotFoundError(f"Model metadata missing: {metadata_path}")

        # Only load artifacts generated by trusted CI workflows.
        # joblib uses pickle and is unsafe for untrusted files.
        self.model = joblib.load(model_path)

        self.metadata = json.loads(metadata_path.read_text())

        self.threshold = float(self.metadata["threshold"])
        self.model_name = self.metadata["model"]

        self.features = self.metadata["features"]

        if not 0 <= self.threshold <= 1:
            raise ValueError("Invalid model threshold")

        if not hasattr(self.model, "predict_proba"):
            raise TypeError("Loaded model does not support probabilities")

    def predict(
        self,
        customers: list[CustomerFeatures],
    ) -> list[PredictionResponse]:
        """Predict churn for one or more customers."""
        records = [customer.model_dump() for customer in customers]

        frame = pd.DataFrame(records)
        frame = frame.reindex(columns=self.features)

        probabilities = np.asarray(self.model.predict_proba(frame)[:, 1])

        results = []

        for probability in probabilities:
            probability = float(probability)
            prediction = int(probability >= self.threshold)

            if probability >= 0.7:
                risk = "high"
            elif probability >= 0.3:
                risk = "medium"
            else:
                risk = "low"

            results.append(
                PredictionResponse(
                    prediction=prediction,
                    churn_probability=probability,
                    threshold=self.threshold,
                    risk_level=risk,
                    model_name=self.model_name,
                )
            )

        return results
