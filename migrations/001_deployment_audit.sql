
-- MLForge deployment auditing
-- Migration 001
-- Additive migration: existing tables remain unchanged.

BEGIN;

CREATE TABLE IF NOT EXISTS model_deployment_audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_run_id BIGINT NOT NULL,
    model_version VARCHAR(64) NOT NULL,
    previous_version VARCHAR(64) NOT NULL,
    training_commit VARCHAR(40) NOT NULL,
    quality_gate_run_id BIGINT NOT NULL,
    approved_by VARCHAR(128),
    render_deployment_id VARCHAR(128),
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_deployment_audit_github_run
        UNIQUE (github_run_id),

    CONSTRAINT ck_deployment_audit_status
        CHECK (
            status IN (
                'approved',
                'deploying',
                'verified',
                'failed',
                'rollback_started',
                'rolled_back',
                'rollback_failed'
            )
        )
);

CREATE TABLE IF NOT EXISTS model_deployment_audit_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_id INTEGER NOT NULL
        REFERENCES model_deployment_audit(id),
    status VARCHAR(32) NOT NULL,
    render_deployment_id VARCHAR(128),
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_deployment_audit_created
    ON model_deployment_audit (created_at DESC);

CREATE INDEX IF NOT EXISTS ix_deployment_audit_events_audit
    ON model_deployment_audit_events (audit_id, timestamp DESC);

COMMIT;
